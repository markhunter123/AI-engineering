#!/usr/bin/env node
/**
 * merge-zh-caps.js — combine translation parts into vendor/figures/zh-figure-caps.js
 *
 * Parts: scripts/zh-caps/part-*.js, each `module.exports = { 'figure-key': '中文…', ... };`
 * Validation against scripts/zh-caps/_caps.json (from extract-figure-caps.js):
 *   - unknown keys → hard error
 *   - untranslated figure keys → listed (expected for figures with no caption:
 *     figures-site-big.js widgets, iso-machine, rlhf-pipeline)
 * Output: window.AIFS_FIG_ZH map, sorted by key.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, 'zh-caps');
const OUT = path.join(__dirname, '..', 'vendor', 'figures', 'zh-figure-caps.js');

const caps = JSON.parse(fs.readFileSync(path.join(DIR, '_caps.json'), 'utf8'));

const parts = fs.readdirSync(DIR).filter((f) => /^part-.*\.js$/.test(f)).sort();
const zh = {};
for (const p of parts) {
  const mod = require(path.join(DIR, p));
  for (const [k, v] of Object.entries(mod)) {
    if (!(k in caps)) {
      console.error('ERROR: unknown figure key "' + k + '" in ' + p);
      process.exit(1);
    }
    if (typeof v !== 'string' || !v.trim()) {
      console.error('ERROR: empty translation for "' + k + '" in ' + p);
      process.exit(1);
    }
    if (k in zh) {
      console.error('ERROR: duplicate key "' + k + '" in ' + p);
      process.exit(1);
    }
    zh[k] = v;
  }
}

// figure keys with no long caption to translate (see _missing.txt)
const SKIP = new Set(['iso-machine', 'rlhf-pipeline',
  'tokenizer-bpe', 'ngram-machine', 'attention-matrix', 'embedding-arithmetic',
  'transformer-block', 'attention-lookup', 'token-strip', 'loss-curve',
  'embedding-projection', 'kv-cache']);

const total = Object.keys(caps).filter((k) => !SKIP.has(k)).length;
const untranslated = Object.keys(caps).filter((k) => !SKIP.has(k) && !(k in zh));
const extra = Object.keys(zh).filter((k) => SKIP.has(k));

console.log('translatable figure keys: ' + total);
console.log('translated: ' + Object.keys(zh).length + '  untranslated: ' + untranslated.length);
if (untranslated.length) {
  console.log('missing:\n' + untranslated.map((k) => '  ' + k + ' (' + caps[k].file + ')').join('\n'));
}
if (extra.length) console.log('skipped keys also present in parts (ok): ' + extra.join(', '));

const lines = Object.keys(zh).sort()
  .map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(zh[k]));
const banner = '/* zh-figure-caps.js — Chinese long-description overrides for interactive figures.\n'
  + ' * Generated by scripts/merge-zh-caps.js from scripts/zh-caps/part-*.js — edit\n'
  + ' * the parts, not this file. Loaded on /zh/ pages only (see layout.js);\n'
  + ' * lesson-figures.js swaps .lf-cap text after mount. en pages never load it. */\n'
  + "'use strict';\n"
  + 'window.AIFS_FIG_ZH = {\n' + lines.join(',\n') + '\n};\n';
fs.writeFileSync(OUT, banner, 'utf8');
console.log('wrote ' + OUT + ' (' + Object.keys(zh).length + ' entries, ' + (banner.length / 1024).toFixed(0) + ' KB)');
